#!/usr/bin/env python3
"""Build a generic, credential-free prototype and optionally stage the USB installer."""
import argparse
import datetime as dt
import fcntl
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[1]

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--stage-web', action='store_true', help='Copy this generic build into docs/ for the installer')
    parser.add_argument('--esphome', default=os.environ.get('TRIVIAPOD_ESPHOME_BINARY', 'esphome'))
    args = parser.parse_args()
    work = ROOT / '.build'; work.mkdir(exist_ok=True)
    with (work / 'build.lock').open('a') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        state_path = work / 'version-state.json'
        state = json.loads(state_path.read_text()) if state_path.exists() else {}
        published_path = ROOT / 'docs/version.json'
        published = json.loads(published_path.read_text()) if published_path.exists() else {}
        number = max(int(state.get('number', 0)), int(published.get('build_number', 0))) + 1
        now = dt.datetime.now(dt.timezone.utc)
        release = (ROOT / 'firmware-release.txt').read_text().strip()
        version = f'{release}+b{number:04d}.{now:%Y%m%dT%H%M%SZ}'
        identity = {'project': 'menemy.triviapod-demo', 'version': version,
                    'display_version': f'{release} b{number:04d}', 'build_number': number,
                    'built_utc': now.strftime('%Y-%m-%d %H:%M:%S UTC'),
                    'build_short': now.strftime('%d %b %H:%M:%S UTC'), 'esphome': '2026.9.1'}
        state_path.write_text(json.dumps({'number': number, 'last_attempt': identity}, indent=2)+'\n')
        config_path = ROOT / 'triviapod-demo.yaml'; config = config_path.read_text()
        config, count = re.subn(r'(?m)^    version: "[^"\n]*" # GENERATED_BUILD_VERSION$',
                                '    version: '+json.dumps(version)+' # GENERATED_BUILD_VERSION', config)
        assert count == 1, 'Missing unique project-version marker'
        config_path.write_text(config)
        constants = {'PROJECT':identity['project'],'VERSION':version,'DISPLAY_VERSION':identity['display_version'],
                     'BUILD_UTC':identity['built_utc'],'BUILD_SHORT':identity['build_short']}
        header = '#pragma once\n// Generated by tools/build.py. No credentials.\nnamespace trivia_version {\n'
        header += ''.join(f'inline constexpr char {key}[] = {json.dumps(value)};\n' for key,value in constants.items())
        (ROOT/'version_info.h').write_text(header+'}\n')
        # Every deployable build comes only from this generic root: no !secret or owner package.
        inputs = [config_path, *(ROOT/'packages').glob('*.yaml')]
        assert all('!secret' not in path.read_text() for path in inputs)
        for path in inputs:
            text = path.read_text()
            assert not re.search(r'(?m)^\s*(ssid|password|key|encryption)\s*:', text), 'Generic build cannot embed credentials: '+str(path)
            for literal in re.findall(r'(?m)^\s*url:\s*(https?://\S+)', text):
                assert literal == 'http://example.invalid/snapshot.jpg', 'Set camera URL at runtime, not in a public image'
        print('Building '+version, flush=True)
        while shutil.which('pgrep') and subprocess.run(['pgrep','-x','hyperfine'],stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL).returncode == 0:
            time.sleep(20)
        log = work / f'build-b{number:04d}.log'
        with log.open('wb') as out:
            result = subprocess.run([args.esphome,'compile',str(config_path)],cwd=ROOT,stdout=out,stderr=subprocess.STDOUT)
        if result.returncode:
            print('Build failed; see '+str(log),file=sys.stderr)
            return result.returncode
        dest = work / 'releases' / version; dest.mkdir(parents=True)
        built = ROOT/'.esphome/.esphome/build/triviapod-demo/build'
        images = {}
        for name in ['firmware.factory.bin','firmware.ota.bin']:
            target=dest/name;shutil.copyfile(built/name,target)
            digest=hashlib.sha256(target.read_bytes()).hexdigest()
            images[name]={'bytes':target.stat().st_size,'sha256':digest,'sha256_prefix':digest[:8]}
        source_paths = [ROOT/'triviapod-demo.yaml',ROOT/'version_info.h',ROOT/'firmware-release.txt',ROOT/'requirements.txt',
                        *ROOT.glob('*.h'),*(ROOT/'packages').glob('*.yaml'),*(ROOT/'components').rglob('*.py'),
                        *(ROOT/'components').rglob('*.h'),*(ROOT/'components').rglob('*.cpp'),ROOT/'tools/build.py',
                        ROOT/'fonts/NotoSans.ttf',ROOT/'fonts/OFL.txt']
        sources={str(path.relative_to(ROOT)):hashlib.sha256(path.read_bytes()).hexdigest() for path in source_paths}
        metadata={**identity,'images':images,'source_sha256':sources,
                  'hardware_validation':'Exported generic/provisioning build not yet flashed; hardware basis tested on one TP-01-A',
                  'prototype':True,'credentials':'No Wi-Fi credentials,API key,household URL or unit MAC embedded'}
        (dest/'build.json').write_text(json.dumps(metadata,indent=2)+'\n')
        if args.stage_web:
            web=ROOT/'docs'; firmware=web/'firmware';firmware.mkdir(exist_ok=True)
            name='triviapod-demo.factory.bin';shutil.copyfile(dest/'firmware.factory.bin',firmware/name)
            # Immutable image URL prevents a browser/CDN from reusing an older download.
            for previous in firmware.glob('triviapod-demo-????????.factory.bin'):
                previous.unlink()
            immutable_name='triviapod-demo-'+images['firmware.factory.bin']['sha256_prefix']+'.factory.bin'
            shutil.copyfile(dest/'firmware.factory.bin',firmware/immutable_name)
            (firmware/'build.json').write_text(json.dumps(metadata,indent=2)+'\n')
            (firmware/'SHA256SUMS').write_text(images['firmware.factory.bin']['sha256']+'  '+name+'\n')
            manifest={'name':'TriviaPOD Prototype','version':version,'home_assistant_domain':'esphome',
                      'new_install_prompt_erase':True,'new_install_improv_wait_time':20,
                      'builds':[{'chipFamily':'ESP32-S3','parts':[{'path':'firmware/'+immutable_name,'offset':0}]}]}
            (web/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
            (web/'version.json').write_text(json.dumps({**identity,'factory_sha256':images['firmware.factory.bin']['sha256']},indent=2)+'\n')
        print(json.dumps({'artifact_directory':str(dest),**identity,'images':images},indent=2),flush=True)
        return 0

if __name__=='__main__':sys.exit(main())
